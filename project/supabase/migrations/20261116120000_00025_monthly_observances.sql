-- ============================================================
-- Monthly Hindu observances on the Star Calendar.
--
--   monthly_observances   one row per event and date: Amavasai, Pournami,
--                         Ekadashi, Pradosham, Sankatahara Chaturthi, Sashti,
--                         Maadha Shivaratri. Imported from
--                         data/vp-trust-monthly-events-2026-2036.csv
--                         (1113 rows, 2026-11-15 to 2036-11-14).
--   app_users.show_observances   each user's Show / Hide events choice.
--
-- Admin overrides: override_date moves an event, is_hidden hides it, note
-- adds a remark, source = 'manual' marks an event an admin added.
--
-- Safe to re-run: the seed uses ON CONFLICT (date, event_key) DO NOTHING, so
-- it adds no duplicates and never overwrites an admin's changes. Later years
-- are imported from Settings -> Calendar -> Import observances CSV.
-- Only admins can add, change or delete rows; everyone signed in can read.
-- ============================================================

CREATE TABLE IF NOT EXISTS monthly_observances (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  date date NOT NULL,
  event_key text NOT NULL CHECK (event_key IN ('amavasai', 'pournami', 'ekadashi', 'pradosham', 'sankatahara', 'sashti', 'shivaratri')),
  event_en text NOT NULL,
  event_ta text NOT NULL,
  is_hidden boolean NOT NULL DEFAULT false,
  override_date date,
  note text,
  source text NOT NULL DEFAULT 'csv' CHECK (source IN ('csv', 'manual')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS monthly_observances_date_event_key ON monthly_observances (date, event_key);
CREATE INDEX IF NOT EXISTS idx_monthly_observances_override_date ON monthly_observances (override_date) WHERE override_date IS NOT NULL;
DROP TRIGGER IF EXISTS monthly_observances_updated_at ON monthly_observances;
CREATE TRIGGER monthly_observances_updated_at BEFORE UPDATE ON monthly_observances
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

ALTER TABLE monthly_observances ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "monthly_observances_select" ON monthly_observances;
CREATE POLICY "monthly_observances_select" ON monthly_observances FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS "monthly_observances_insert" ON monthly_observances;
CREATE POLICY "monthly_observances_insert" ON monthly_observances FOR INSERT TO authenticated WITH CHECK (current_app_role() = 'admin');
DROP POLICY IF EXISTS "monthly_observances_update" ON monthly_observances;
CREATE POLICY "monthly_observances_update" ON monthly_observances FOR UPDATE TO authenticated USING (current_app_role() = 'admin') WITH CHECK (current_app_role() = 'admin');
DROP POLICY IF EXISTS "monthly_observances_delete" ON monthly_observances;
CREATE POLICY "monthly_observances_delete" ON monthly_observances FOR DELETE TO authenticated USING (current_app_role() = 'admin');

ALTER TABLE app_users ADD COLUMN IF NOT EXISTS show_observances boolean NOT NULL DEFAULT true;

